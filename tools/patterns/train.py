"""Train the pattern rolls from the corpus (corpus.py): writes dsp/patterns.c.

  1. The library: every distinct line of each role (kick, snare, hat, fourth part) in the corpus, as a hit mask and a
     ghost mask over 16 or 32 steps (a two-bar line whose bars are the same is one bar). Each role's lines are ordered
     from sparse to busy, and within the same busyness each next to the most similar (Hamming distance over two bars):
     a pattern's neighbours are its variations, so a knob or a modulation on it moves to a busier or sparser
     relative, never a random jump.
  2. The entries: each corpus entry as indices into the library, with its genre, tempo, swing and weight. The roll
     (params.c) walks them as a decision tree: an entry by weight, then for each role either that entry's line or one
     from an entry whose earlier choices are near the ones made (a kernel over the Hamming distances: the
     conditional distributions the corpus implies, smoothed so new combinations that keep its rules appear).

Run: python3 tools/patterns/train.py   (from the repository's root)
"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from corpus import CORPUS

ROLES = ["K", "S", "H", "T"]
GENRES = ["house", "breakbeat", "dnb", "hiphop", "funk", "latin", "indie"]   # (the engine's PG_*: the same order)

def parse(line):
    bars = line.split("|")
    for b in bars:
        assert len(b) == 16 and set(b) <= set("xo."), line
    if len(bars) == 2 and bars[0] == bars[1]:
        bars = bars[:1]
    s = "".join(bars)
    hit = sum(1 << i for i, c in enumerate(s) if c in "xo")
    ghost = sum(1 << i for i, c in enumerate(s) if c == "o")
    return (hit, ghost, len(s))

def two_bars(p):
    hit, ghost, n = p
    if n == 16:
        hit |= hit << 16; ghost |= ghost << 16
    return hit, ghost

def dist(a, b):
    ha, ga = two_bars(a); hb, gb = two_bars(b)
    return bin(ha ^ hb).count("1") + .5 * bin(ga ^ gb).count("1")

def busy(p):
    hit, ghost, n = two_bars(p) + (p[2],)
    return (bin(hit & ~ghost).count("1") + .4 * bin(ghost).count("1")) / 2.0

def order(lines):
    """sparse to busy; within a step of busyness (0.5 hits a bar), a chain of nearest neighbours"""
    lines = sorted(set(lines), key=lambda p: (busy(p), p))
    out = []
    buckets = {}
    for p in lines:
        buckets.setdefault(round(busy(p) * 2) / 2, []).append(p)
    for b in sorted(buckets):
        left = buckets[b][:]
        cur = min(left, key=lambda p: dist(p, out[-1])) if out else left[0]
        while left:
            left.remove(cur); out.append(cur)
            if left:
                cur = min(left, key=lambda p: (dist(p, cur), p))
    return out

def main():
    from lib_v107 import LIB_V107
    lib = {}
    for r in ROLES:
        lines = [parse(e[r]) for e in CORPUS if e[r] is not None and e[r].replace("|", "").strip(".")]
        lib[r] = order(lines)
    entries = []
    for e in sorted(CORPUS, key=lambda e: GENRES.index(e["genre"])):   # (stable: by genre, each in corpus order)
        idx = []
        for r in ROLES:
            if e[r] is None or not e[r].replace("|", "").strip("."):
                idx.append(0)                       # linear (an empty line: the drum left to the stream)
            else:
                idx.append(lib[r].index(parse(e[r])) + 1)
        entries.append((GENRES.index(e["genre"]), idx, e))
    fams = sorted({e["fam"] for _, _, e in entries if e.get("fam")})   # (1.0.8) each family an id, 1..; a hand-written entry 0
    root = os.path.join(os.path.dirname(__file__), "..", "..")
    out = []
    w = out.append
    w("/* SPDX-License-Identifier: MPL-2.0 */")
    w("/* GENERATED by tools/patterns/train.py from tools/patterns/corpus.py and families.py: do not edit. The pattern")
    w(" * library (each role's lines, sparse to busy, neighbours alike), the corpus entries the rolls walk (params.c), by")
    w(" * genre, each genre's lines of each role, and the 1.0.5..1.0.7 library's lines in this one (old patches). */")
    w('#include "synth.h"')
    w("")
    off = 0
    offs = []
    w("const PatLine PAT_LIB[] = {")
    for r in ROLES:
        offs.append(off)
        w(f"    /* {r}: {len(lib[r])} lines */")
        for p in lib[r]:
            hit, ghost, n = p
            vis = "".join("o" if ghost >> i & 1 else "x" if hit >> i & 1 else "." for i in range(n))
            w(f"    {{0x{hit:08X}u, 0x{ghost:08X}u, {n}}},   /* {vis[:16]}{' ' + vis[16:] if n == 32 else ''} */")
        off += len(lib[r])
    w("};")
    w(f"const uint16_t PAT_OFF[NUM_DRUMS] = {{{', '.join(map(str, offs))}}};")
    w(f"const uint16_t PAT_CNT[NUM_DRUMS] = {{{', '.join(str(len(lib[r])) for r in ROLES)}}};")
    w("")
    w("/* the entries, by genre (" + ", ".join(f"{i} {g}" for i, g in enumerate(GENRES)) + "): each role's line (1-based;")
    w(" * 0 linear), BPM low and high, swing low and high (hundredths), the swing's level (8 or 16), weight (tenths), its")
    w(" * family (an era or sub-style, 1..; 0 a hand-written entry, a family of its own) */")
    w("const PatEntry PAT_ENT[] = {")
    for g, idx, e in entries:
        wt = max(1, int(round(e['w'] * 10)))
        w(f"    {{{g}, {{{', '.join(map(str, idx))}}}, {e['bpm'][0]}, {e['bpm'][1]}, {int(round(e['sw'][0] * 100))}, "
          f"{int(round(e['sw'][1] * 100))}, {e['lev']}, {wt}, {fams.index(e['fam']) + 1 if e.get('fam') else 0}}},   /* {e['name']} */")
    w("};")
    w(f"const int PAT_NENT = {len(entries)};")
    goff = [0]
    for i in range(len(GENRES)):
        goff.append(goff[-1] + sum(1 for x in entries if x[0] == i))
    w(f"const uint16_t PAT_GOFF[NUM_PG + 1] = {{{', '.join(map(str, goff))}}};   /* each genre's entries: [g] .. [g + 1] */")
    # each genre's lines of each role (a close variation stays in its genre's corpus)
    use, uoff = [], [0]
    for gi in range(len(GENRES)):
        for ri in range(len(ROLES)):
            ls = sorted({idx[ri] for g, idx, _ in entries if g == gi and idx[ri]})
            use += ls
            uoff.append(len(use))
    w(f"const uint16_t PAT_USE[] = {{{', '.join(map(str, use))}}};")
    w(f"const uint16_t PAT_UOFF[NUM_PG * NUM_DRUMS + 1] = {{{', '.join(map(str, uoff))}}};   /* genre g, role d: [g * 4 + d] .. +1 */")
    # the old library's lines here (a patch saved by 1.0.5..1.0.7): each its new index, 1-based (0 never: every old line is kept)
    v107, voff = [], []
    for ri, r in enumerate(ROLES):
        voff.append(len(v107))
        for (h, gh, n) in LIB_V107[ri]:
            p = (h, gh, n)
            assert p in lib[r], ("a 1.0.7 line is gone", r, hex(h))
            v107.append(lib[r].index(p) + 1)
    w(f"const uint16_t PAT_V107[] = {{{', '.join(map(str, v107))}}};")
    w(f"const uint8_t PAT_V107_OFF[NUM_DRUMS] = {{{', '.join(map(str, voff))}}}, "
      f"PAT_V107_CNT[NUM_DRUMS] = {{{', '.join(str(len(LIB_V107[i])) for i in range(4))}}};")
    path = os.path.join(root, "dsp", "patterns.c")
    open(path, "w").write("\n".join(out) + "\n")
    # the report
    print(f"corpus: {len(CORPUS)} entries:", ", ".join(f"{g} {sum(1 for x in entries if x[0] == i)}" for i, g in enumerate(GENRES)))
    for r in ROLES:
        print(f"library {r}: {len(lib[r])} lines (busyness {busy(lib[r][0]):.1f} .. {busy(lib[r][-1]):.1f} hits a bar), "
              f"mean neighbour distance {sum(dist(a, b) for a, b in zip(lib[r], lib[r][1:])) / max(1, len(lib[r]) - 1):.1f}")
    assert len(fams) < 256 and max(len(lib[r]) for r in ROLES) < 256
    print(f"families: {len(fams)}")
    print("wrote", os.path.relpath(path))

if __name__ == "__main__":
    main()
