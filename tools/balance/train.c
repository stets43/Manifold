/* Balance's table: for each motion, the long-run energy of a note against the mean note's, by its distance from the
   frame's centre and its place in pitch (dsp/balance_tab.h). Built on the host with the DSP sources and a table of
   ones (Balance then does nothing), from rolls of every curated style, layer 1 alone:

     cc -O2 -DPLAT_HOST -Idsp -I<fm1-base>/include -o train tools/balance/train.c dsp/*.c -lm && ./train > dsp/balance_tab.h
*/
#include <stdio.h>
#include <stdlib.h>
#include <math.h>
#include "synth.h"
static Synth S;
int main(void) {
    static float L[SUB], R[SUB];
    double sum[NUM_GENS][5][4] = {{{0}}}, cnt[NUM_GENS][5][4] = {{{0}}};
    for (int fn = 0; fn < NUM_GENS; fn++)
        for (int st = 1; st < 8; st++)
            for (int sd = 0; sd < 12; sd++) {
                synth_init(&S, 99u); synth_set_style(&S, st); synth_randomize(&S, (uint32_t)(sd * 7919 + fn * 131 + st * 17 + 5), 0.f);
                S.target[P_G1_FUNC] = ((float)fn + .5f) / g_param_meta[P_G1_FUNC].hi;
                S.target[P_G1_BAL] = .5f;
                S.target[P_G2_ENERGY] = 0.f;
                for (int i = 0; i < NUM_PARAMS; i++) S.base[i] = S.mod[i] = S.target[i];
                params_cache_all(&S); engine_build(&S); S.transport = 1;
                double acc[MAX_NODES] = {0};
                for (int b = 0; b < 48000 * 8 / SUB; b++) {
                    synth_process(&S, L, R, SUB);
                    if (b < 400) continue;
                    for (int i = 0; i < S.eng.n_nodes; i++) { float a = S.layer[0].g.a[i]; acc[i] += a * a; }
                }
                const Engine *e = &S.eng; int N = e->n_nodes; double mean = 0;
                for (int i = 0; i < N; i++) mean += acc[i];
                mean /= N; if (mean <= 0) continue;
                float lo = 1e9f, hi = -1e9f;
                for (int i = 0; i < N; i++) { if (e->node[i].lr < lo) lo = e->node[i].lr; if (e->node[i].lr > hi) hi = e->node[i].lr; }
                float span = hi - lo > .1f ? hi - lo : 1.f;
                for (int i = 0; i < N; i++) {
                    const Node *nd = &e->node[i];
                    float p = (nd->lr - lo) / span, dx = nd->x - e->fcx, dy = nd->y - e->fcy;
                    float rd = sqrtf(dx * dx + dy * dy) / (e->fext > 1e-4f ? e->fext : 1.f);
                    int pb = (int)(p * 4.f); if (pb > 3) pb = 3;
                    int rb = (int)(rd * 5.f); if (rb > 4) rb = 4;
                    sum[fn][rb][pb] += acc[i] / mean; cnt[fn][rb][pb] += 1;
                }
            }
    printf("/* Balance's table (gen.c): for each motion, how much energy a note gets over a long run, against the mean note's, by\n"
           "   its distance from the frame's centre (5 steps of a fifth of the frame's half-width, the last everything past 0.8)\n"
           "   and its place in pitch among the notes (4 quarters, lowest first). Generated by tools/balance/train.c from rolls\n"
           "   of every curated style (12 a style a motion, layer 1 alone); Balance divides it out (Balanced), then leans toward\n"
           "   the bass (Dark) or the middle (Bright). Each bin is shrunk toward 1 by eight notes' worth. */\n");
    printf("#define BAL_R 5\n#define BAL_P 4\nstatic const float BAL_EXP[NUM_GENS][BAL_R][BAL_P] = {\n");
    for (int fn = 0; fn < NUM_GENS; fn++) {
        printf("    {");
        for (int r = 0; r < 5; r++) {
            printf("{");
            for (int p = 0; p < 4; p++) {
                /* (shrunk toward 1 by eight notes' worth: a bin seen a few times says little) */
                double v = (sum[fn][r][p] + 8.0) / (cnt[fn][r][p] + 8.0);
                if (v < .2) v = .2; if (v > 5.) v = 5.;
                printf("%.3ff%s", v, p < 3 ? ", " : "");
            }
            printf("}%s", r < 4 ? ", " : "");
        }
        printf("},   /* %s */\n", gen_name(fn));
    }
    printf("};\n");
    return 0;
}
